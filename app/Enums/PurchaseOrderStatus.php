<?php

namespace App\Enums;

/**
 * A purchase order's workflow status. PartiallyReceived/Received are set
 * exclusively by PurchaseOrderService::recalculateReceiptStatus(), called
 * from GoodsReceiveService::create() after every GRN — never set
 * directly by a Livewire component.
 */
enum PurchaseOrderStatus: string
{
    case Draft = 'draft';
    case Sent = 'sent';
    case PartiallyReceived = 'partially_received';
    case Received = 'received';
    case Cancelled = 'cancelled';

    public function label(): string
    {
        return match ($this) {
            self::Draft => 'Draft',
            self::Sent => 'Sent',
            self::PartiallyReceived => 'Partially Received',
            self::Received => 'Received',
            self::Cancelled => 'Cancelled',
        };
    }

    public function color(): string
    {
        return match ($this) {
            self::Draft => 'gray',
            self::Sent => 'blue',
            self::PartiallyReceived => 'yellow',
            self::Received => 'green',
            self::Cancelled => 'red',
        };
    }

    public static function options(): array
    {
        return array_combine(
            array_map(fn (self $case) => $case->value, self::cases()),
            array_map(fn (self $case) => $case->label(), self::cases()),
        );
    }
}
